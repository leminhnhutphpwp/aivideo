const nodeTypes: NodeTypes = { sceneNode: SceneNode };

export function MultiSceneEditor({ editUuid, initialMode }: { editUuid: string | null; initialMode?: string | null }) {
  const router = useRouter();
  const addToast = useToastStore(s => s.addToast);

  const { nodes, setNodes, onNodesChange, edges, setEdges, onEdgesChange } = useCanvasState();
  const { sceneFormData, setSceneFormData, updateField: updateFormField } = useSceneForm();
  const [selectedNodeId, setSelectedNodeId] = useState<string | null>(null);
  const rfInstance = useRef<any>(null);
  const { pushHistory, undo, redo } = useUndoRedo(setNodes, setEdges);

  const dirtyRef = useRef(false);
  const markDirty = useCallback(() => { dirtyRef.current = true; }, []);

  const [title, setTitleState] = useState('');
  const [videoType, setVideoTypeState] = useState('none');
  const [totalDuration, setTotalDurationState] = useState(10);

  const setTitle = useCallback((v: string) => { markDirty(); setTitleState(v); }, [markDirty]);
  const setVideoType = useCallback((v: string) => { markDirty(); setVideoTypeState(v); }, [markDirty]);
  const setTotalDuration = useCallback((v: number) => { markDirty(); setTotalDurationState(v); }, [markDirty]);
  const [sharedCamera, setSharedCamera] = useState('');
  const [sharedStyle, setSharedStyle] = useState('');
  const [sharedMood, setSharedMood] = useState('');
  const [sharedLighting, setSharedLighting] = useState('');
  const [sharedNarration, setSharedNarration] = useState('');
  const [drivingAudio, setDrivingAudio] = useState('');
  const [firstFrameImage, setFirstFrameImage] = useState('');
  const [lastFrameImage, setLastFrameImage] = useState('');
  const [storyboardImage, setStoryboardImage] = useState('');
  const [multiPanelAutoGenerated, setMultiPanelAutoGenerated] = useState(false);
  const [voiceMood, setVoiceMood] = useState('');
  const [voiceId, setVoiceId] = useState('');
  const [editSb, setEditSb] = useState<any>(null);
  const [templates, setTemplates] = useState<any[]>([]);
  const [typeOptions, setTypeOptions] = useState<{ value: string; label: string }[]>([]);
  const [options, setOptions] = useState<{ durations: number[] }>({ durations: [] });
  const [durationTiers, setDurationTiers] = useState<number[]>([]);
  const [showLoading, setShowLoading] = useState(true);
  const [loadProgress, setLoadProgress] = useState(0);
  const [sceneRefPreviews, setSceneRefPreviews] = useState<Record<string, string>>({});

  const [ctxMenu, setCtxMenu] = useState<any>(null);
  const [showGrid, setShowGrid] = useState(true);
  const [layersExpanded, setLayersExpanded] = useState(true);
  const [mobileLayersOpen, setMobileLayersOpen] = useState(false);
  const [toolsOpen, setToolsOpen] = useState(false);
  const [openBasic, setOpenBasic] = useState(true);
  const [openCamera, setOpenCamera] = useState(false);
  const [openAudio, setOpenAudio] = useState(false);
  const [openRef, setOpenRef] = useState(false);
  const [saving, setSaving] = useState(false);

  const { renderMode, setRenderMode } = useRenderMode();
  const { compiledPrompt, compileStatus, compilePrompt, markStale, setCompiledPrompt, setCompileStatus } = useCompilePrompt();
  const { planTier, tier } = useTierConfig();
  const { zoom } = useZoomTracker(rfInstance as any);

  useLoadStoryboard({
    editUuid, setNodes, setEdges, setSceneFormData, setTitle, setVideoType,
    setVoiceMood, setVoiceId, setEditSb, setTemplates, setTypeOptions,
    setOptions, setDurationTiers, setShowLoading, setLoadProgress,
    setTotalDuration, setSharedCamera, setSharedStyle, setSharedMood,
    setSharedLighting, setSharedNarration, setDrivingAudio, setFirstFrameImage,
    setLastFrameImage, setCompiledPrompt, setCompileStatus, setRenderMode,
    setStoryboardImage, setMultiPanelAutoGenerated,
  });

  useEffect(() => {
    if (initialMode === 'single' || initialMode === 'multi' || initialMode === 'storyboard') {
      if (initialMode === 'single') setRenderMode('single_flow');
      else if (initialMode === 'storyboard') setRenderMode('storyboard_image');
      // multi_scene is disabled for launch — `?mode=multi` falls back to One-Shot.
      else if (MULTI_SCENE_ENABLED) setRenderMode('multi_scene');
      else setRenderMode('single_flow');
    }
  }, []);

  useEffect(() => {
    const mode = renderMode === 'single_flow' ? 'single' : renderMode === 'storyboard_image' ? 'storyboard' : 'multi';
    const params = new URLSearchParams(window.location.search);
    if (params.get('mode') !== mode) {
      params.set('mode', mode);
      const newUrl = `${window.location.pathname}?${params.toString()}`;
      window.history.replaceState(null, '', newUrl);
    }
  }, [renderMode]);

  const { selectedEdge, setSelectedEdge, editingEdgeLabel, setEditingEdgeLabel, deleteEdge, saveEdgeLabel } = useEdgeManager(setEdges, setSceneFormData);

  const addScene = useCallback((parentKey?: string | null) => {
    markDirty();
    if (renderMode === 'single_flow') markStale();
    const key = genId();
    const pNode = parentKey ? nodes.find(n => n.id === parentKey) : null;
    const x = pNode ? pNode.position.x + 280 : 80 + Math.random() * 200;
    const siblings = parentKey ? edges.filter(e => e.source === parentKey).length : nodes.filter(n => !edges.some(e => e.target === n.id)).length;
    const y = pNode ? pNode.position.y + siblings * 180 : 80 + nodes.length * 60;
    setNodes(nds => [...nds, { id: key, type: 'sceneNode', position: { x, y }, data: { nodeId: key, sceneNumber: nds.length + 1, duration: 5, prompt: '', aspect_ratio: '16:9', camera_movement: '', style: '', has_reference: false, has_narration: false, refPreview: null, onDelete: actionsRef.current.del, onDuplicate: actionsRef.current.dup, onAddChild: actionsRef.current.add } }]);
    setSceneFormData(prev => ({ ...prev, [key]: initForm(key) }));
    setSelectedNodeId(key);
    if (parentKey) {
      const label = renderMode === 'single_flow' ? 'Chuyển tiếp' : undefined;
      setEdges(eds => [...eds, { id: `e-${parentKey}-${key}`, source: parentKey, target: key, type: 'smoothstep', markerEnd: { type: MarkerType.ArrowClosed }, style: { stroke: '#ffffff14', strokeWidth: 1.5 }, label }]);
      setSceneFormData(prev => ({ ...prev, [key]: { ...prev[key], parent_key: parentKey, edge_label: label || null } }));
    }
  }, [nodes, edges, setNodes, setEdges, setSceneFormData, renderMode, markStale, markDirty]);

  const deleteScene = useCallback((nodeId: string) => {
    markDirty();
    if (renderMode === 'single_flow') markStale();
    edges.filter(e => e.source === nodeId).forEach(e => deleteScene(e.target));
    setNodes(nds => nds.filter(n => n.id !== nodeId));
    setEdges(eds => eds.filter(e => e.source !== nodeId && e.target !== nodeId));
    setSceneFormData(prev => { const n = { ...prev }; delete n[nodeId]; return n; });
    if (selectedNodeId === nodeId) setSelectedNodeId(null);
  }, [setNodes, setEdges, setSceneFormData, selectedNodeId, edges, renderMode, markStale, markDirty]);

  const duplicateScene = useCallback((nodeId: string) => {
    markDirty();
    if (renderMode === 'single_flow') markStale();
    const src = nodes.find(n => n.id === nodeId);
    const f = sceneFormData[nodeId];
    if (!src || !f) return;
    const key = genId();
    setNodes(nds => [...nds, { id: key, type: 'sceneNode', position: { x: src.position.x + 40, y: src.position.y + 60 }, data: { ...src.data, nodeId: key, sceneNumber: nds.length + 1, onDelete: actionsRef.current.del, onDuplicate: actionsRef.current.dup, onAddChild: actionsRef.current.add } }]);
    setSceneFormData(prev => ({ ...prev, [key]: { ...f, _key: key, parent_key: null } }));
    setSelectedNodeId(key);
  }, [nodes, sceneFormData, setNodes, setSceneFormData, renderMode, markStale, markDirty]);

  const onConnect = useCallback((c: Connection) => {
    if (c.source === c.target) return;
    markDirty();
    if (renderMode === 'single_flow') markStale();
    const edgeLabel = renderMode === 'single_flow' ? 'Chuyển tiếp' : undefined;
    setEdges(eds => eds.filter(e => e.target !== c.target));
    setEdges(eds => [...eds, { id: `e-${c.source}-${c.target}`, source: c.source!, target: c.target!, type: 'smoothstep', animated: true, markerEnd: { type: MarkerType.ArrowClosed, color: '#ffffff30' }, style: { stroke: '#ffffff14', strokeWidth: 1.5 }, label: edgeLabel }]);
    setSceneFormData(prev => ({ ...prev, [c.target!]: { ...prev[c.target!], parent_key: c.source!, edge_label: edgeLabel || null } }));
  }, [setEdges, setSceneFormData, renderMode, markStale, markDirty]);

  const onNodeClick = useCallback((_e: any, n: Node) => setSelectedNodeId(n.id), []);
  const onNodeContextMenu = useCallback((ev: any, node: Node) => { ev.preventDefault(); setSelectedNodeId(node.id); setCtxMenu({ x: ev.clientX, y: ev.clientY, nodeId: node.id }); }, []);

  const lastClickRef = useRef(0);
  const onPaneClickWrapper = useCallback((ev: any) => {
    const now = Date.now();
    if (now - lastClickRef.current < 300) {
      markDirty();
      if (renderMode === 'single_flow') markStale();
      const rf = rfInstance.current;
      if (!rf) return;
      const pos = rf.screenToFlowPosition({ x: ev.clientX || window.innerWidth / 2, y: ev.clientY || window.innerHeight / 2 });
      const key = genId();
      setNodes(nds => [...nds, { id: key, type: 'sceneNode', position: pos, data: { nodeId: key, sceneNumber: nds.length + 1, duration: 5, prompt: '', aspect_ratio: '16:9', camera_movement: '', style: '', has_reference: false, has_narration: false, refPreview: null, onDelete: actionsRef.current.del, onDuplicate: actionsRef.current.dup, onAddChild: actionsRef.current.add } }]);
      setSceneFormData(prev => ({ ...prev, [key]: initForm(key) }));
      setSelectedNodeId(key);
    } else {
      setSelectedNodeId(null); setCtxMenu(null); setSelectedEdge(null);
    }
    lastClickRef.current = now;
  }, [setNodes, setSceneFormData, renderMode, markStale, markDirty]);

  const updateField = useCallback((key: string, field: string, value: any) => {
    markDirty();
    updateFormField(key, field, value);
    setNodes(nds => nds.map(n => n.id === key ? { ...n, data: { ...n.data, [field]: value, has_reference: field === 'reference_image' ? !!value : n.data.has_reference, has_narration: field === 'narration' ? !!value : n.data.has_narration } } : n));
    if (field === 'edge_label') setEdges(eds => eds.map(e => e.target === key ? { ...e, label: value || undefined } : e));
    if (renderMode === 'single_flow') markStale();
  }, [updateFormField, setNodes, setEdges, renderMode, markStale, markDirty]);

  const updateSharedSkill = useCallback((field: string, value: string) => {
    markDirty();
    const setters: Record<string, (v: string) => void> = { camera_movement: setSharedCamera, style: setSharedStyle, mood: setSharedMood, lighting: setSharedLighting, narration: setSharedNarration };
    if (setters[field]) setters[field](value);
    setSceneFormData(prev => { const next = { ...prev }; Object.keys(next).forEach(k => { next[k] = { ...next[k], [field]: value }; }); return next; });
    setNodes(nds => nds.map(n => ({ ...n, data: { ...n.data, [field]: value, has_narration: field === 'narration' ? !!value : n.data.has_narration } })));
    if (renderMode === 'single_flow') markStale();
  }, [setSceneFormData, setNodes, renderMode, markStale, markDirty]);

  const onEdgeClick = useCallback((_ev: any, edge: Edge) => {
    _ev.stopPropagation();
    setSelectedNodeId(null); setCtxMenu(null);
    setSelectedEdge({ id: edge.id, source: edge.source, target: edge.target, label: (edge.label as string) || undefined, x: _ev.clientX, y: _ev.clientY });
    setEditingEdgeLabel((edge.label as string) || '');
  }, [setSelectedNodeId, setSelectedEdge, setEditingEdgeLabel]);

  const { aiModalOpen, setAiModalOpen, aiConcept, setAiConcept, aiLoading, handleAiDraft } = useAiDraft({
    setNodes, setEdges, setSceneFormData, addToast,
    markStale: renderMode === 'single_flow' ? markStale : undefined,
    renderMode,
  });

  const { templateOpen, setTemplateOpen, pendingTemplate, setPendingTemplate, importTemplate } = useTemplateImport({
    setNodes, setEdges, setSceneFormData, addToast, rfInstance,
    markStale: renderMode === 'single_flow' ? markStale : undefined,
    renderMode,
  });

  const { pickerOpen, setPickerOpen, openRefPicker, handleRefSelect } = useReferencePicker({
    setNodes, setSceneRefPreviews, setSceneFormData,
  });

  const { actionsRef } = useSyncRefs({
    nodes, edges, setNodes, sceneRefPreviews, deleteScene, duplicateScene, addScene,
  });

  useAutoTags(nodes, edges, setNodes);
  const { playbackActive, handlePlayback } = usePlayback();

  const sceneCount = nodes.length;
  const calcTotalDuration = nodes.reduce((s, n) => s + ((n.data as any)?.duration || 5), 0);
  const effectiveTotalDuration = renderMode === 'single_flow' ? totalDuration : calcTotalDuration;
  const { priceData, priceLoading } = useCreditEstimation({
    sceneCount, totalDuration: effectiveTotalDuration, planTier, renderMode: renderMode as 'multi_scene' | 'single_flow' | 'storyboard_image', durationTiers,
  });

  useKeyboardShortcuts({
    selectedNodeId, selectedEdge, ctxMenu, saving,
    deleteScene: (id: string) => deleteScene(id),
    deleteEdge: (id: string) => deleteEdge(id),
    handleSave: () => handleSave(),
  });

  useEffect(() => {
    const handler = (e: BeforeUnloadEvent) => {
      if (dirtyRef.current) {
        e.preventDefault();
        e.returnValue = ''; // Firefox/Safari require a returnValue to show the prompt.
      }
    };
    window.addEventListener('beforeunload', handler);
    return () => window.removeEventListener('beforeunload', handler);
  }, []);

  const handleAutoLayout = () => {
    let x = 80, y = 80, c = 0;
    setNodes(nds => nds.map(n => { const p = { x, y }; c++; if (c >= 3) { c = 0; y += 200; x = 80; } else x += 280; return { ...n, position: p }; }));
  };
  const handleFitView = () => rfInstance.current?.fitView({ padding: 0.3, duration: 300 });
  const handleZoomIn = () => rfInstance.current?.zoomIn({ duration: 200 });
  const handleZoomOut = () => rfInstance.current?.zoomOut({ duration: 200 });

  const buildPayload = useCallback(() => {
    const base = buildBasePayload({
      title, videoType, planTier, voiceMood, voiceId,
      renderMode: renderMode as 'multi_scene' | 'single_flow' | 'storyboard_image',
      nodes, edges, sceneFormData,
    });
    if (renderMode === 'single_flow' || renderMode === 'storyboard_image') {
      return {
        ...base,
        total_duration: totalDuration,
        camera_movement: sharedCamera || undefined,
        style: sharedStyle || undefined,
        mood: sharedMood || undefined,
        lighting: sharedLighting || undefined,
        narration: sharedNarration || undefined,
        driving_audio: drivingAudio || undefined,
        first_frame_image: firstFrameImage || undefined,
        last_frame_image: lastFrameImage || undefined,
        shot_type: renderMode === 'storyboard_image' ? 'multi' : undefined,
        multi_panel_image: renderMode === 'storyboard_image' ? (storyboardImage || undefined) : undefined,
        scenes: nodes.map(node => {
          const f = sceneFormData[node.id] || initForm(node.id);
          const pe = edges.find(e => e.target === node.id);
          return { ...f, _key: node.id, parent_key: pe?.source || null, position_x: node.position.x, position_y: node.position.y, camera_movement: '', style: '', mood: '', lighting: '', narration: '' };
        }),
      };
    }
    return base;
  }, [title, videoType, planTier, voiceMood, voiceId, renderMode, nodes, edges, sceneFormData, totalDuration, sharedCamera, sharedStyle, sharedMood, sharedLighting, sharedNarration, drivingAudio, firstFrameImage, lastFrameImage, storyboardImage]);

  const handleSave = useCallback(async () => {
    // Panel image is now OPTIONAL: if the user provides none, the backend auto-generates
    // it at render time (2-stage pipeline) — so no hard block here.
    setSaving(true);
    try {
      await handleSaveMulti({ editSb, title, nodes, buildPayload, addToast, router, renderMode });
      dirtyRef.current = false;
    } catch (e: any) {
      addToast(e?.message || 'Lỗi lưu storyboard', 'error');
    } finally { setSaving(false); }
  }, [editSb, title, nodes, buildPayload, addToast, router, renderMode, storyboardImage]);

  const handleUploadFile = useCallback(async (file: File): Promise<string> => {
    const project = await daemon.createProject({ name: `storyboard-upload-${Date.now()}` });
    const result: any = await daemon.uploadFile(project.id, file);
    return result.filename || result.name || file.name;
  }, []);

  const [generatingMultiPanel, setGeneratingMultiPanel] = useState(false);

  const handleGenerateMultiPanel = useCallback(async () => {
    setGeneratingMultiPanel(true);
    try {
      // Bootstrap: if the storyboard isn't saved yet, create it in place (no separate
      // "save" step, no panel image needed) so the AI has a real storyboard to work on.
      let sb = editSb;
      if (!sb) {
        if (!title.trim()) { addToast('Vui lòng nhập tiêu đề trước khi tạo ảnh', 'warning'); return; }
        if (nodes.length < 1) { addToast('Cần ít nhất 1 cảnh trước khi tạo ảnh', 'warning'); return; }
        sb = await laravel.createStoryboard(buildPayload());
        setEditSb(sb);
        // Keep state; reflect the new uuid in the URL (builder edit mode = ?id=…) so a
        // refresh stays in the builder instead of jumping to the render view.
        window.history.replaceState(null, '', `/studio/storyboard/flow?id=${sb.uuid}`);
        dirtyRef.current = false;
      }
      const result = await laravel.generateMultiPanelImage(sb.uuid);
      setStoryboardImage(result.multi_panel_image);
      setMultiPanelAutoGenerated(false);
      addToast('Đã tạo ảnh multi-panel thành công', 'success');
    } catch (e: any) {
      addToast(e?.message || 'Lỗi tạo ảnh multi-panel', 'error');
    } finally {
      setGeneratingMultiPanel(false);
    }
  }, [editSb, title, nodes, buildPayload, addToast, setStoryboardImage]);

  const handleRender = useCallback(async () => {
    if ((renderMode === 'single_flow' || renderMode === 'storyboard_image') && (!compiledPrompt || compileStatus !== 'compiled')) {
      addToast('Vui lòng compile prompt trước khi render', 'warning');
      return;
    }
    if (!editSb) { addToast('Vui lòng lưu storyboard trước khi render', 'warning'); return; }
    try {
      await handleRenderMulti({ editSb, addToast, router });
    } catch (e: any) {
      addToast(e?.message || 'Lỗi render storyboard', 'error');
    }
  }, [editSb, addToast, router, renderMode, compiledPrompt, compileStatus]);

  // ---- Derived state ----
  const selectedScene = selectedNodeId ? sceneFormData[selectedNodeId] : null;
  const selectedNode = selectedNodeId ? nodes.find(n => n.id === selectedNodeId) : null;
  const hasIncomingEdge = selectedNodeId ? edges.some(e => e.target === selectedNodeId) : false;
  const hasRefImage = selectedNodeId ? !!selectedScene?.reference_image : false;
  const hasNarr = selectedNodeId ? !!selectedScene?.narration : false;

  const styledEdges = edges.map(edge => {
    const isTargetSelected = edge.target === selectedNodeId;
    return {
      ...edge,
      animated: true,
      className: isTargetSelected ? 'edge-path-selected' : '',
      style: {
        stroke: isTargetSelected ? '#FF5A1F' : 'rgba(255, 255, 255, 0.08)',
        strokeWidth: isTargetSelected ? 2 : 1.5,
        transition: 'stroke 0.3s, stroke-width 0.3s',
      },
      markerEnd: {
        type: MarkerType.ArrowClosed,
        color: isTargetSelected ? '#FF5A1F' : 'rgba(255, 255, 255, 0.15)',
      },
    };
  });

  // ---- Render ----
  if (showLoading) return <LoadingScreen isEditing={!!editSb} loadProgress={loadProgress} />;

  const pushHistoryEffect = () => { pushHistory(nodes, edges); };

  return (
    <div className="h-full w-full flex flex-col bg-zinc-950">
      <h1 className="sr-only">Trình tạo video Storyboard</h1>
      {/* Top Toolbar */}
      <div className="h-11 md:h-12 flex items-center gap-1.5 md:gap-2 px-2 md:px-4 border-b border-white/[0.06] bg-[#18181B] shrink-0 z-20">
        <button onClick={() => setMobileLayersOpen(true)} className="md:hidden p-1.5 rounded-lg hover:bg-white/[0.06] text-slate-500 hover:text-slate-300 transition-colors cursor-pointer shrink-0">
          <Menu className="h-4 w-4" />
        </button>
        <button onClick={() => router.push('/studio/storyboard')} className="p-1.5 rounded-lg hover:bg-white/[0.06] text-slate-500 hover:text-slate-300 transition-colors cursor-pointer shrink-0"><ArrowLeft className="h-4 w-4" /></button>
        <span className="text-[10px] font-bold text-slate-500 tracking-wider mr-1 shrink-0 hidden sm:inline">{editSb ? 'SỬA' : 'MỚI'}</span>
        <input value={title} onChange={e => setTitle(e.target.value)} placeholder="Nhập tiêu đề..." className="bg-transparent text-xs md:text-sm font-semibold text-white placeholder-slate-600 outline-none min-w-0 flex-1" />

        {/* AI — luôn hiện */}
        <button onClick={() => setAiModalOpen(true)} disabled={aiLoading}
          className="h-8 cursor-pointer flex items-center gap-1 md:gap-1.5 px-2 md:px-3 rounded-xl text-[10px] md:text-[11px] font-medium transition-all
            bg-gradient-to-r from-[#FF5A1F]/10 to-[#FF8A5B]/5 border border-[#FF5A1F]/20 hover:border-[#FF5A1F]/40
            text-[#FF5A1F] hover:text-[#FF8A5B] shrink-0">
          {aiLoading ? <Loader2 className="h-3 w-3 animate-spin" /> : <Sparkles className="h-3 w-3" />}
          <span>AI</span>
        </button>

        {/* Mode (One-Shot / Multi-Panel) — luôn hiện */}
        <div className="shrink-0"><RenderModeToggle /></div>

        {/* Công cụ phụ — gom vào menu ⋯ để toolbar không tràn */}
        <div className="relative shrink-0">
          <button onClick={() => setToolsOpen(v => !v)} title="Công cụ"
            className={cn("h-8 w-8 flex items-center justify-center rounded-xl border transition-all cursor-pointer",
              toolsOpen ? "bg-white/[0.08] border-white/[0.2] text-white" : "bg-white/[0.03] border-white/[0.08] hover:border-white/[0.15] text-slate-400 hover:text-white")}>
            <MoreHorizontal className="h-4 w-4" />
          </button>
          {toolsOpen && (
            <>
              <div className="fixed inset-0 z-40" onClick={() => setToolsOpen(false)} />
              <div className="absolute right-0 top-10 z-50 w-64 rounded-xl border border-white/10 bg-zinc-900 shadow-xl p-3 space-y-3">
                {/* Hoàn tác / Zoom */}
                <div className="flex items-center justify-between">
                  <div className="flex items-center gap-0.5">
                    <button onClick={() => { pushHistoryEffect(); undo(); }} className="cursor-pointer p-1.5 rounded-lg hover:bg-white/[0.06] text-slate-400" title="Hoàn tác (Ctrl+Z)"><Undo2 className="h-4 w-4" /></button>
                    <button onClick={() => { pushHistoryEffect(); redo(); }} className="cursor-pointer p-1.5 rounded-lg hover:bg-white/[0.06] text-slate-400" title="Làm lại (Ctrl+Shift+Z)"><Redo2 className="h-4 w-4" /></button>
                  </div>
                  <div className="flex items-center gap-0.5">
                    <button onClick={handleZoomOut} className="cursor-pointer p-1.5 rounded-lg hover:bg-white/[0.06] text-slate-400" title="Thu nhỏ"><ZoomOut className="h-4 w-4" /></button>
                    <span className="text-[10px] text-slate-500 tabular-nums w-9 text-center">{Math.round(zoom * 100)}%</span>
                    <button onClick={handleZoomIn} className="cursor-pointer p-1.5 rounded-lg hover:bg-white/[0.06] text-slate-400" title="Phóng to"><ZoomIn className="h-4 w-4" /></button>
                    <button onClick={handleFitView} className="cursor-pointer p-1.5 rounded-lg hover:bg-white/[0.06] text-slate-400" title="Hiển thị tất cả"><Maximize2 className="h-4 w-4" /></button>
                  </div>
                </div>

                {/* Loại video */}
                <div className="space-y-1">
                  <label className="text-[10px] font-semibold text-slate-500 uppercase tracking-wider">Loại video</label>
                  <CustomSelect value={videoType} onChange={setVideoType}
                    options={typeOptions.length > 0 ? typeOptions : [{ value: 'storyboard_video', label: 'Kịch bản' }]}
                    className="w-full" pill />
                </div>

                {/* Thời lượng (single-flow) */}
                {renderMode === 'single_flow' && durationTiers.length > 0 && (
                  <div className="space-y-1">
                    <label className="text-[10px] font-semibold text-slate-500 uppercase tracking-wider">Thời lượng</label>
                    <CustomSelect value={String(totalDuration)} onChange={(v) => setTotalDuration(Number(v))}
                      options={durationTiers.map((d: number) => ({ value: String(d), label: `${d}s` }))}
                      className="w-full" pill />
                  </div>
                )}

                {/* Chất lượng */}
                <div className="space-y-1">
                  <label className="text-[10px] font-semibold text-slate-500 uppercase tracking-wider">Chất lượng</label>
                  <div className="flex items-center gap-2">
                    <span className={cn("inline-flex items-center gap-1.5 px-2.5 py-1 rounded-lg border font-bold tracking-wide select-none", tier.bg, tier.border, tier.text)}>
                      <tier.icon className={cn("h-3.5 w-3.5", tier.iconColor)} />
                      <span className="text-[11px]">{tier.label}</span>
                    </span>
                  </div>
                  <p className="text-[10px] text-slate-500 leading-relaxed">{tier.desc}</p>
                </div>

                {/* Mẫu có sẵn */}
                {templates.length > 0 && (
                  <button onClick={() => { setTemplateOpen(true); setToolsOpen(false); }}
                    className="w-full h-8 flex items-center justify-center gap-1.5 rounded-xl bg-white/[0.03] border border-white/[0.08] hover:border-white/[0.15] text-[11px] text-slate-300 hover:text-white transition-all cursor-pointer">
                    <Film className="h-3.5 w-3.5" /> Mẫu có sẵn
                  </button>
                )}
              </div>
            </>
          )}
        </div>

        {/* Render (khi sửa storyboard đã lưu) */}
        {editSb && ['draft', 'analyzed'].includes(editSb.status) && (
          <button onClick={handleRender}
            className="h-8 flex items-center gap-1.5 px-3 rounded-xl text-[11px] text-white font-semibold transition-all bg-gradient-to-r from-[#FF5A1F] to-[#FF6B35] hover:from-[#FF6B35] hover:to-[#FF7B45] shadow-[0_2px_12px_rgba(255,90,31,0.25)] hover:shadow-[0_4px_20px_rgba(255,90,31,0.35)] shrink-0 cursor-pointer"><Play className="h-3 w-3" /><span className="hidden sm:inline">Render</span></button>
        )}

        {/* Credits */}
        <div className="flex items-center gap-1.5 px-2.5 py-1 rounded-lg bg-[#FF5A1F]/5 border border-[#FF5A1F]/10 shrink-0">
          {priceLoading ? <Loader2 className="h-3 w-3 text-[#FF5A1F] animate-spin" /> : <Coins className="h-3 w-3 text-[#FF5A1F]" />}
          <span className="text-[10px] font-semibold text-[#FF5A1F] tabular-nums">
            {priceData?.pricing?.total_credits !== undefined
              ? priceData.pricing.total_credits.toLocaleString()
              : priceData?.total !== undefined
              ? priceData.total.toLocaleString()
              : sceneCount === 0 ? '0' : '...'}
          </span>
        </div>

        {/* Lưu storyboard (không render — render là nút riêng ở trên) */}
        <button onClick={handleSave} disabled={saving}
          className="cursor-pointer h-8 flex items-center gap-1.5 px-3 rounded-xl text-[11px] text-white font-semibold transition-all bg-gradient-to-r from-[#FF5A1F] to-[#FF6B35] hover:from-[#FF6B35] hover:to-[#FF7B45] shadow-[0_2px_12px_rgba(255,90,31,0.25)] hover:shadow-[0_4px_20px_rgba(255,90,31,0.35)] shrink-0 disabled:opacity-50 disabled:cursor-not-allowed">
          {saving ? <Loader2 className="h-3 w-3 animate-spin" /> : <Save className="h-3 w-3" />} Lưu</button>
      </div>

      <div className="flex flex-1 overflow-hidden">
        {/* Mobile Layers Overlay */}
        <AnimatePresence>
          {mobileLayersOpen && (
            <>
              <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }}
                className="fixed inset-0 bg-zinc-950/60 backdrop-blur-sm z-40 md:hidden" onClick={() => setMobileLayersOpen(false)} />
              <motion.div initial={{ x: -300 }} animate={{ x: 0 }} exit={{ x: -300 }} transition={{ type: 'spring', damping: 30, stiffness: 300 }}
                className="fixed top-0 left-0 bottom-0 w-72 bg-[#121212] border-r border-white/[0.06] z-50 md:hidden flex flex-col shadow-md">
                <div className="flex items-center justify-between px-3 h-12 border-b border-white/[0.04]">
                  <span className="text-[10px] font-bold text-slate-500 tracking-wider">CẢNH</span>
                  <button onClick={() => setMobileLayersOpen(false)} className="p-1.5 rounded-lg hover:bg-white/[0.04] text-slate-600"><X className="h-4 w-4" /></button>
                </div>
                <div className="flex items-center gap-2 px-3 py-2.5 border-b border-white/[0.04] bg-white/[0.01]">
                  <CustomSelect value={videoType} onChange={setVideoType}
                    options={typeOptions.length > 0 ? typeOptions : [{ value: 'none', label: 'None' }, { value: 'storyboard_video', label: 'Kịch bản' }]}
                    className="flex-1" pill />
                  <span className={cn("flex items-center gap-1 px-2 py-1 rounded-lg border shrink-0", tier.bg, tier.border, tier.text)}>
                    <tier.icon className={cn("h-3 w-3", tier.iconColor)} />
                    <span className="text-[9px] font-semibold">{tier.label}</span>
                  </span>
                </div>
                <div className="flex-1 overflow-y-auto py-1">
                  {nodes.map((node, i) => {
                    const c = COLORS[i % COLORS.length]; const p = (node.data as any)?.prompt;
                    return (
                      <div key={node.id} onClick={() => { setSelectedNodeId(node.id); onNodeClick({} as any, node); setMobileLayersOpen(false); }}
                        className={cn("flex items-center gap-2.5 px-3 py-2.5 cursor-pointer transition-colors group min-h-[44px]", selectedNodeId === node.id ? "bg-white/[0.04]" : "hover:bg-white/[0.02]")}>
                        <div className="w-5 h-5 rounded-md flex items-center justify-center text-[9px] font-bold shrink-0" style={{ backgroundColor: c + '22', color: c }}>{i + 1}</div>
                        <span className={cn("text-[11px] flex-1", selectedNodeId === node.id ? "text-slate-200" : "text-slate-500")}>{p || 'Cảnh mới'}</span>
                        <button onClick={e => { e.stopPropagation(); deleteScene(node.id); }} className="p-1 rounded hover:bg-red-500/15 text-slate-600 hover:text-red-400 transition-all"><svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.5"><path d="M3 6h18M19 6v14c0 1-1 2-2 2H7c-1 0-2-1-2-2V6M8 6V4c0-1 1-2 2-2h4c1 0 2 1 2 2v2"/></svg></button>
                      </div>)
                  })}
                </div>
                <div className="border-t border-white/[0.04] p-3">
                  <button onClick={() => { addScene(null); setMobileLayersOpen(false); }} className="w-full flex items-center justify-center gap-2 px-2 py-3 rounded-xl border border-white/[0.08] hover:border-white/[0.14] bg-white/[0.02] hover:bg-white/[0.04] text-[11px] text-slate-400 hover:text-slate-200 transition-all min-h-[44px]"><Plus className="h-3.5 w-3.5" /> Thêm cảnh</button>
                </div>
              </motion.div>
            </>
          )}
        </AnimatePresence>

        {/* Left Panel - Layers (tablet/desktop) */}
        <div className={cn("border-r border-white/[0.06] bg-[#121212] transition-all duration-300 shrink-0 flex-col z-10 hidden md:flex", layersExpanded ? "w-52" : "w-10")}>
          <div className="flex items-center justify-between px-3 h-10 border-b border-white/[0.04]">
            {layersExpanded && <span className="text-[10px] font-bold text-slate-500 tracking-wider">CẢNH</span>}
            <button onClick={() => setLayersExpanded(!layersExpanded)} className="cursor-pointer p-1 rounded hover:bg-white/[0.04] text-slate-600">{layersExpanded ? <ChevronDown className="h-3.5 w-3.5" /> : <ChevronRight className="h-3.5 w-3.5" />}</button>
          </div>
          {layersExpanded && (
            <div className="flex-1 overflow-y-auto py-1">
              {nodes.map((node, i) => {
                const c = COLORS[i % COLORS.length]; const p = (node.data as any)?.prompt;
                return (
                  <div key={node.id} onClick={() => { setSelectedNodeId(node.id); onNodeClick({} as any, node); }}
                    className={cn("flex items-center gap-2.5 px-3 py-2 cursor-pointer transition-colors group", selectedNodeId === node.id ? "bg-white/[0.04]" : "hover:bg-white/[0.02]")}>
                    <div className="w-5 h-5 rounded-md flex items-center justify-center text-[9px] font-bold shrink-0" style={{ backgroundColor: c + '22', color: c }}>{i + 1}</div>
                    <span className={cn("text-[11px] truncate flex-1", selectedNodeId === node.id ? "text-slate-200" : "text-slate-500")}>{p || 'Cảnh mới'}</span>
                    <button onClick={e => { e.stopPropagation(); deleteScene(node.id); }} className="opacity-0 group-hover:opacity-100 p-0.5 rounded hover:bg-red-500/15 text-slate-600 hover:text-red-400 transition-all"><svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2"><path d="M3 6h18M19 6v14c0 1-1 2-2 2H7c-1 0-2-1-2-2V6M8 6V4c0-1 1-2 2-2h4c1 0 2 1 2 2v2"/></svg></button>
                  </div>)
              })}
            </div>
          )}
          {layersExpanded && (
            <div className="border-t border-white/[0.04] p-2">
              <button onClick={() => addScene(null)} className="w-full flex items-center gap-2 px-2 py-2 rounded-xl border border-white/[0.08] hover:border-white/[0.14] bg-white/[0.02] hover:bg-white/[0.04] text-[11px] text-slate-400 hover:text-slate-200 transition-all cursor-pointer"><Plus className="h-3.5 w-3.5" /> Thêm cảnh</button>
            </div>
          )}
        </div>

        {/* Canvas */}
        <div className="flex-1 relative bg-zinc-950">
          <ReactFlowProvider>
            <ReactFlow
              proOptions={{ hideAttribution: true }}
              nodes={nodes} edges={styledEdges}
              onNodesChange={onNodesChange} onEdgesChange={onEdgesChange}
              onConnect={onConnect} onNodeClick={onNodeClick} onPaneClick={onPaneClickWrapper}
              onNodeContextMenu={onNodeContextMenu}
              onEdgeClick={onEdgeClick}
              nodeTypes={nodeTypes} fitView fitViewOptions={{ maxZoom: 1, padding: 0.3 }} minZoom={0.08} maxZoom={2}
              onInit={(inst) => { rfInstance.current = inst; }}
              snapToGrid snapGrid={[15, 15]}
              defaultEdgeOptions={{ type: 'smoothstep', markerEnd: { type: MarkerType.ArrowClosed, color: '#ffffff30' }, style: { stroke: '#ffffff14', strokeWidth: 1.5 } }}
            >
              <Background variant={BackgroundVariant.Dots} gap={24} size={1} color="#ffffff06" style={{ opacity: showGrid ? 1 : 0, transition: 'opacity 0.3s' }} />
              <Controls className={cn("!bg-[#18181B] !border !border-white/[0.08] !rounded-2xl !shadow-md !overflow-hidden", "[&_button]:!bg-[#18181B] [&_button]:!border-b [&_button]:!border-white/[0.08] last:[&_button]:!border-b-0", "[&_svg]:!fill-slate-400 hover:[&_svg]:!fill-white", "hover:[&_button]:!bg-white/[0.06] [&_button]:!transition-colors")} position="bottom-right" showInteractive={false} />
              <MiniMap className="!bg-[#18181B] !border-white/[0.08] !rounded-2xl !shadow-sm" nodeColor="#FF5A1F40" maskColor="rgba(15, 15, 20, 0.7)" position="bottom-left" />
            </ReactFlow>
          </ReactFlowProvider>

          <button onClick={() => addScene(null)} className="cursor-pointer absolute md:top-4 md:right-4 bottom-4 right-4 z-10 w-12 h-12 md:w-10 md:h-10 rounded-2xl bg-[#18181B] border border-white/[0.08] hover:border-white/[0.15] flex items-center justify-center text-slate-400 hover:text-white shadow-sm transition-all hover:scale-105">
            <Plus className="h-5 w-5" /></button>

          <AnimatePresence>{ctxMenu && <CtxMenu x={ctxMenu.x} y={ctxMenu.y} nodeId={ctxMenu.nodeId} onClose={() => setCtxMenu(null)} onAddChild={addScene} onDuplicate={duplicateScene} onDelete={deleteScene} />}</AnimatePresence>
          <EdgeLabelPopup edge={selectedEdge} label={editingEdgeLabel} onLabelChange={setEditingEdgeLabel} onSave={saveEdgeLabel} onDelete={deleteEdge} onClose={() => setSelectedEdge(null)} />
        </div>

        {/* Right Panel */}
        {renderMode === 'single_flow' && !selectedScene && (
          <CompiledPromptPanel
            compiledPrompt={compiledPrompt}
            status={compileStatus}
            onCompile={() => { if (editSb) { compilePrompt(editSb.uuid); } else { addToast('Vui lòng lưu storyboard trước khi compile', 'warning'); } }}
            onEdit={(prompt: string) => setCompiledPrompt(prompt)}
            sceneCount={nodes.length}
            totalDuration={effectiveTotalDuration}
            sharedCamera={sharedCamera}
            sharedStyle={sharedStyle}
            sharedMood={sharedMood}
            sharedLighting={sharedLighting}
            sharedNarration={sharedNarration}
            onSharedSkillChange={updateSharedSkill}
            drivingAudio={drivingAudio}
            onDrivingAudioChange={setDrivingAudio}
            firstFrameImage={firstFrameImage}
            onFirstFrameImageChange={setFirstFrameImage}
            lastFrameImage={lastFrameImage}
            onLastFrameImageChange={setLastFrameImage}
            onUploadFile={handleUploadFile}
          />
        )}
        {renderMode === 'storyboard_image' && !selectedScene && (
          <StoryboardImagePanel
            multiPanelImageUrl={storyboardImage || null}
            onMultiPanelImageChange={(url) => { markDirty(); setStoryboardImage(url); setMultiPanelAutoGenerated(false); }}
            autoGenerated={multiPanelAutoGenerated}
            onUseOwnImage={() => { markDirty(); setMultiPanelAutoGenerated(false); }}
            onUploadFile={handleUploadFile}
            onGenerateMultiPanel={handleGenerateMultiPanel}
            generatingMultiPanel={generatingMultiPanel}
            compiledPrompt={compiledPrompt}
            onCompile={() => { if (editSb) { compilePrompt(editSb.uuid); } else { addToast('Vui lòng lưu storyboard trước khi compile', 'warning'); } }}
            onEdit={(prompt: string) => { markDirty(); setCompiledPrompt(prompt); }}
            sceneCount={nodes.length}
            totalDuration={effectiveTotalDuration}
            sharedCamera={sharedCamera}
            sharedStyle={sharedStyle}
            sharedMood={sharedMood}
            sharedLighting={sharedLighting}
            sharedNarration={sharedNarration}
            onSharedSkillChange={updateSharedSkill}
            drivingAudio={drivingAudio}
            onDrivingAudioChange={setDrivingAudio}
            firstFrameImage={firstFrameImage}
            onFirstFrameImageChange={setFirstFrameImage}
            lastFrameImage={lastFrameImage}
            onLastFrameImageChange={setLastFrameImage}
          />
        )}
        {selectedScene && selectedNode && selectedNodeId && (
          <MultiScenePropertyPanel
            selectedScene={selectedScene}
            selectedNode={selectedNode}
            hasIncomingEdge={hasIncomingEdge}
            selectedNodeId={selectedNodeId}
            sceneRefPreviews={sceneRefPreviews}
            onClose={() => setSelectedNodeId(null)}
            openBasic={openBasic} onToggleBasic={() => setOpenBasic(!openBasic)}
            openCamera={openCamera} onToggleCamera={() => setOpenCamera(!openCamera)}
            openAudio={openAudio} onToggleAudio={() => setOpenAudio(!openAudio)}
            openRef={openRef} onToggleRef={() => setOpenRef(!openRef)}
            updateField={updateField}
            openRefPicker={openRefPicker}
            options={options}
            renderMode={renderMode as 'multi_scene' | 'single_flow'}
          />
        )}
        {!selectedScene && renderMode !== 'single_flow' && renderMode !== 'storyboard_image' && (
          <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} className="w-10 border-l border-white/[0.04] bg-zinc-950/85 backdrop-blur-xl hidden lg:flex items-center justify-center shrink-0 z-10">
            <span className="text-[9px] text-slate-600 select-none [writing-mode:vertical-lr] rotate-180 tracking-widest font-bold uppercase">THUỘC TÍNH</span>
          </motion.div>
        )}
      </div>

      <BottomBar showGrid={showGrid} onToggleGrid={() => setShowGrid(!showGrid)} onAutoLayout={handleAutoLayout}
        playbackActive={playbackActive} onPlayback={() => handlePlayback(nodes, edges, rfInstance.current, setSelectedNodeId)}
        nodeCount={nodes.length} />

      <TemplateModal open={templateOpen} templates={templates} hasExistingNodes={nodes.length > 0}
        onSelect={(tpl) => { if (nodes.length > 0) { setPendingTemplate(tpl); return; } importTemplate(tpl); }}
        onClose={() => setTemplateOpen(false)} />

      <ConfirmMergeModal open={!!pendingTemplate}
        templateName={pendingTemplate?.name || ''} templateSceneCount={pendingTemplate?.scenes?.length || 0}
        existingNodeCount={nodes.length}
        onCancel={() => setPendingTemplate(null)}
        onAppend={() => { const t = pendingTemplate; setPendingTemplate(null); importTemplate(t, nodes.length); }}
        onReplace={() => { const t = pendingTemplate; setPendingTemplate(null); setNodes([]); setEdges([]); setSceneFormData({}); resetIdCounter(); setTimeout(() => importTemplate(t, 0), 50); }} />

      <AiDraftModal open={aiModalOpen} concept={aiConcept} onConceptChange={setAiConcept}
        onClose={() => setAiModalOpen(false)} onSubmit={() => handleAiDraft(videoType, nodes)} submitting={aiLoading} />

      <ReferencePicker open={pickerOpen} onClose={() => setPickerOpen(false)}
        onSelect={handleRefSelect} acceptTypes="image/*" maxSizeMB={50}
        featureLabel="Storyboard" canUpload={true} />
    </div>
  );
}
