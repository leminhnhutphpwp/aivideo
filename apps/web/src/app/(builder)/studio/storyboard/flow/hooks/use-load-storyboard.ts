'use client';

import { useEffect, useRef } from 'react';
import { MarkerType, type Node, type Edge } from '@xyflow/react';
import { laravel, daemon } from '@/lib/api/client';
import type { SceneFormData } from '@/lib/api/storyboard-types';

import type { RenderMode } from '../../components/render-mode-provider';

interface LoadStoryboardParams {
  editUuid: string | null;
  setNodes: any;
  setEdges: any;
  setSceneFormData: any;
  setTitle: (v: string) => void;
  setVideoType: (v: string) => void;
  setVoiceMood: (v: string) => void;
  setVoiceId: (v: string) => void;
  setEditSb: (v: any) => void;
  setTemplates: (v: any[]) => void;
  setTypeOptions: (v: any[]) => void;
  setOptions: (v: any) => void;
  setDurationTiers: (v: number[]) => void;
  setShowLoading: (v: boolean) => void;
  setLoadProgress: (v: number | ((prev: number) => number)) => void;
  setTotalDuration: (v: number) => void;
  setSharedCamera: (v: string) => void;
  setSharedStyle: (v: string) => void;
  setSharedMood: (v: string) => void;
  setSharedLighting: (v: string) => void;
  setSharedNarration: (v: string) => void;
  setDrivingAudio?: (v: string) => void;
  setFirstFrameImage?: (v: string) => void;
  setLastFrameImage?: (v: string) => void;
  setCompiledPrompt?: (v: string | null) => void;
  setCompileStatus?: (v: any) => void;
  setRenderMode?: (v: RenderMode) => void;
  setStoryboardImage?: (v: string) => void;
  setMultiPanelAutoGenerated?: (v: boolean) => void;
}

export function useLoadStoryboard({
  editUuid, setNodes, setEdges, setSceneFormData, setTitle, setVideoType,
  setVoiceMood, setVoiceId, setEditSb, setTemplates, setTypeOptions,
  setOptions, setDurationTiers, setShowLoading, setLoadProgress,
  setTotalDuration, setSharedCamera, setSharedStyle, setSharedMood,
  setSharedLighting, setSharedNarration, setDrivingAudio, setFirstFrameImage,
  setLastFrameImage, setCompiledPrompt, setCompileStatus, setRenderMode,
  setStoryboardImage,
  setMultiPanelAutoGenerated,
}: LoadStoryboardParams) {
  const loadedRef = useRef(false);

  useEffect(() => {
    if (loadedRef.current) return;
    loadedRef.current = true;

    const load = async () => {
      try {
        const skills: any = await daemon.skills().catch(() => ({}));
        const types = skills.storyboard?.types || [];

        laravel.pricingDurations().then((durations: { code: string; seconds: number; name: string }[]) => {
          const seconds = durations.map(d => d.seconds);
          setDurationTiers(seconds);
          setOptions((prev: any) => ({ ...prev, durations: seconds }));
        }).catch(() => {});
        const noneOption = { value: 'none', label: 'None' };
        setTypeOptions([noneOption, ...types.map((t: any) => ({ value: t.id, label: t.label }))]);
        const allTemplates: any[] = [];
        types.forEach((t: any) => {
          (t.templateFlows || []).forEach((f: any) => allTemplates.push({ ...f, typeId: t.id, typeLabel: t.label }));
        });
        setTemplates(allTemplates);

        if (editUuid) {
          const data = await laravel.storyboard(editUuid);
          const sb = data.data || data;
          setEditSb(sb);
          setTitle(sb.title || '');
          setVideoType(sb.video_type || 'none');
          setVoiceMood(sb.voice_mood || '');
          setVoiceId(sb.voice || '');
          setTotalDuration(sb.total_duration || 10);
          if (sb.compiled_prompt) {
            setCompiledPrompt?.(sb.compiled_prompt);
            setCompileStatus?.('compiled');
          }
          setSharedCamera(sb.camera_movement || '');
          setSharedStyle(sb.style || '');
          setSharedMood(sb.mood || '');
          setSharedLighting(sb.lighting || '');
          setSharedNarration(sb.narration || '');
          setDrivingAudio?.(sb.driving_audio || '');
          setFirstFrameImage?.(sb.first_frame_image || '');
          setLastFrameImage?.(sb.last_frame_image || '');
          // System-generated panel image is hidden (path nulled server-side) — keep the
          // storyboard image empty and flag it so the builder shows a "hidden" note instead.
          if (sb.multi_panel_auto_generated) {
            setStoryboardImage?.('');
            setMultiPanelAutoGenerated?.(true);
          } else {
            setStoryboardImage?.(sb.multi_panel_image || '');
            setMultiPanelAutoGenerated?.(false);
          }
          if (sb.render_mode && setRenderMode) {
            setRenderMode(sb.render_mode);
          }

          if (sb.scenes?.length) {
            const nns: Node[] = [];
            const nes: Edge[] = [];
            const nfd: Record<string, SceneFormData> = {};
            const s2k: Record<number, string> = {};
            sb.scenes.forEach((s: any, i: number) => {
              s2k[s.id] = String(s.id);
              nns.push({
                id: String(s.id), type: 'sceneNode',
                position: { x: s.position_x ?? 80 + (i % 2) * 280, y: s.position_y ?? 80 + Math.floor(i / 2) * 200 },
                data: {
                  nodeId: String(s.id), sceneNumber: s.scene_number, duration: s.duration_seconds, prompt: s.prompt,
                  aspect_ratio: s.aspect_ratio, camera_movement: s.camera_movement, style: s.style,
                  has_reference: !!s.reference_image, has_narration: !!s.narration, refPreview: null,
                },
              });
              nfd[String(s.id)] = {
                _key: String(s.id), parent_key: null, prompt: s.prompt, duration_seconds: s.duration_seconds,
                camera_movement: s.camera_movement || '', lighting: s.lighting || '',
                style: s.style || '', mood: s.mood || '',
                negative_prompt: s.negative_prompt || '', reference_image: s.reference_image || '',
                last_frame_image: s.last_frame_image || '', narration: s.narration || '',
                aspect_ratio: s.aspect_ratio || '16:9', resolution: s.resolution || '720p',
                edge_label: null, position_x: s.position_x ?? 100, position_y: s.position_y ?? 100,
              };
            });
            sb.scenes.forEach((s: any) => {
              if (s.parent_scene_id && s2k[s.parent_scene_id] && s2k[s.id]) {
                nes.push({
                  id: `e-${s2k[s.parent_scene_id]}-${s2k[s.id]}`,
                  source: s2k[s.parent_scene_id], target: s2k[s.id],
                  type: 'smoothstep',
                  markerEnd: { type: MarkerType.ArrowClosed, color: '#ffffff30' },
                  style: { stroke: '#ffffff14', strokeWidth: 1.5 },
                  label: s.edge_label || undefined,
                  labelStyle: { fill: '#71717a', fontSize: 10 },
                  labelBgStyle: { fill: '#121212', fillOpacity: 0.95 },
                });
                nfd[s2k[s.id]].parent_key = s2k[s.parent_scene_id];
                nfd[s2k[s.id]].edge_label = s.edge_label;
              }
            });
            setNodes(nns);
            setEdges(nes);
            setSceneFormData(nfd);
          }
        }
      } catch {}
      setLoadProgress(100);
      setTimeout(() => setShowLoading(false), 400);
    };

    const timer = setTimeout(() => setLoadProgress(80), 2000);
    load();
    return () => clearTimeout(timer);
  }, [editUuid]);
}
