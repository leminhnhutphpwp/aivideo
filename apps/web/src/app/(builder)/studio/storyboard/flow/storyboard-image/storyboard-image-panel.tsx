'use client';

import { useState, useRef, useEffect } from 'react';
import { motion } from 'motion/react';
import { cn } from '@/lib/utils';
import {
  Sparkles, Upload, X, ImageIcon, Loader2,
  Camera, Palette, Smile, Sun, Mic, ChevronDown, Music, Info, Wand2, Lock,
} from 'lucide-react';
import { LARAVEL_URL } from '@/lib/api/client';
import { noDownloadImg } from '@/lib/media-protection';
import { RichSelect } from '@/components/studio/rich-select';
import {
  CAMERA_OPTIONS, STYLE_OPTIONS, MOOD_OPTIONS, LIGHTING_OPTIONS,
} from '@/components/studio/options';

interface StoryboardImagePanelProps {
  multiPanelImageUrl: string | null;
  onMultiPanelImageChange: (url: string) => void;
  onUploadFile: (file: File) => Promise<string>;
  onGenerateMultiPanel?: () => Promise<void>;
  generatingMultiPanel?: boolean;
  autoGenerated?: boolean;
  onUseOwnImage?: () => void;
  compiledPrompt: string | null;
  onCompile: () => void;
  onEdit: (prompt: string) => void;
  sceneCount: number;
  totalDuration: number;
  sharedCamera: string;
  sharedStyle: string;
  sharedMood: string;
  sharedLighting: string;
  sharedNarration: string;
  onSharedSkillChange: (field: string, value: string) => void;
  drivingAudio: string;
  onDrivingAudioChange: (url: string) => void;
  firstFrameImage: string;
  onFirstFrameImageChange: (url: string) => void;
  lastFrameImage: string;
  onLastFrameImageChange: (url: string) => void;
}

export function StoryboardImagePanel({
  multiPanelImageUrl,
  onMultiPanelImageChange,
  onUploadFile,
  onGenerateMultiPanel,
  generatingMultiPanel,
  autoGenerated,
  onUseOwnImage,
  compiledPrompt,
  onCompile,
  onEdit,
  sceneCount,
  totalDuration,
  sharedCamera,
  sharedStyle,
  sharedMood,
  sharedLighting,
  sharedNarration,
  onSharedSkillChange,
  drivingAudio,
  onDrivingAudioChange,
  firstFrameImage,
  onFirstFrameImageChange,
  lastFrameImage,
  onLastFrameImageChange,
}: StoryboardImagePanelProps) {
  const [imageOpen, setImageOpen] = useState(true);
  const [skillsOpen, setSkillsOpen] = useState(true);
  const [imageHelpOpen, setImageHelpOpen] = useState(false);
  const [skillsHelpOpen, setSkillsHelpOpen] = useState(false);
  const blobUrlsRef = useRef<string[]>([]);
  const [localPreviewUrl, setLocalPreviewUrl] = useState<string | null>(null);

  const trackBlob = (url: string) => {
    blobUrlsRef.current.push(url);
  };

  const revokeBlobs = () => {
    blobUrlsRef.current.forEach(u => URL.revokeObjectURL(u));
    blobUrlsRef.current = [];
  };

  useEffect(() => {
    return () => revokeBlobs();
  }, []);

  const displayUrl = localPreviewUrl
    || (multiPanelImageUrl?.startsWith('storyboards/')
      ? `${LARAVEL_URL}/storage/${multiPanelImageUrl}`
      : multiPanelImageUrl);

  const handleFileSelect = async (accept: string, onChange: (v: string) => void) => {
    const input = document.createElement('input');
    input.type = 'file';
    input.accept = accept;
    input.onchange = async (e) => {
      const file = (e.target as HTMLInputElement).files?.[0];
      if (!file) return;
      const blobUrl = URL.createObjectURL(file);
      trackBlob(blobUrl);
      setLocalPreviewUrl(blobUrl);
      try {
        const url = await onUploadFile(file);
        onChange(url);
      } catch {
        onChange(blobUrl);
      }
    };
    input.click();
  };

  useEffect(() => {
    const close = () => { setImageHelpOpen(false); setSkillsHelpOpen(false); };
    window.addEventListener('click', close);
    return () => window.removeEventListener('click', close);
  }, []);

  return (
    <motion.div
      initial={{ opacity: 0 }}
      animate={{ opacity: 1 }}
      className="border-l border-white/[0.04] bg-zinc-950/95 backdrop-blur-xl overflow-y-auto z-10
        flex flex-col min-h-0
        md:w-[240px] lg:w-[300px] shrink-0
        [&::-webkit-scrollbar]:w-1 [&::-webkit-scrollbar-track]:bg-transparent [&::-webkit-scrollbar-thumb]:bg-white/10 hover:[&::-webkit-scrollbar-thumb]:bg-white/20 [&::-webkit-scrollbar-thumb]:rounded-full"
    >
      {/* Header */}
      <div className="flex items-center justify-between px-4 py-3.5 border-b border-white/[0.04]">
        <div className="flex items-center gap-2">
          <div className="w-6 h-6 rounded-lg bg-[#FF5A1F]/10 border border-[#FF5A1F]/20 flex items-center justify-center">
            <ImageIcon className="h-3.5 w-3.5 text-[#FF5A1F]" />
          </div>
          <span className="text-xs font-semibold text-white">Multi-Panel</span>
        </div>
      </div>

      {/* Multi-panel image upload — collapsible */}
      <div className="flex items-center justify-between w-full px-4 py-2.5 border-b border-white/[0.04]">
        <button onClick={() => setImageOpen(!imageOpen)} className="flex items-center gap-1 hover:bg-white/[0.02] transition-colors cursor-pointer">
          <div className="relative">
            <Info className="h-3 w-3 text-slate-600 hover:text-slate-400 transition-colors cursor-pointer"
              onClick={(e) => { e.stopPropagation(); setImageHelpOpen(v => !v); setSkillsHelpOpen(false); }} />
            {imageHelpOpen && (
              <div className="absolute bottom-full left-1/2 -translate-x-1/2 mb-2 w-56 bg-[#1C1C20] border border-white/[0.08] rounded-xl shadow-md p-3 z-50">
                <p className="text-[10px] text-slate-300 leading-relaxed">
                  Upload một ảnh duy nhất có bố cục nhiều khung hình (comic strip). Model Wan2.7 tự động nhận diện bố cục và sinh video theo từng khung.
                </p>
              </div>
            )}
          </div>
          <span className="text-[11px] font-semibold text-slate-400">Bảng phân cảnh</span>
        </button>
        <motion.div animate={{ rotate: imageOpen ? 180 : 0 }} transition={{ duration: 0.15 }}>
          <ChevronDown className="h-3.5 w-3.5 text-slate-600" />
        </motion.div>
      </div>
      <motion.div
        initial={false}
        animate={imageOpen ? { height: 'auto', opacity: 1, transitionEnd: { overflow: 'visible' } } : { height: 0, opacity: 0, overflow: 'hidden' }}
        transition={{ duration: 0.2 }}
      >
        <div className="px-4 py-3 space-y-3 border-b border-white/[0.04]">
          {autoGenerated ? (
            <div className="rounded-xl border border-white/[0.06] bg-white/[0.02] px-3 py-4 flex flex-col items-center gap-2 text-center">
              <div className="w-8 h-8 rounded-lg bg-white/[0.04] flex items-center justify-center">
                <Lock className="h-4 w-4 text-slate-500" />
              </div>
              <p className="text-[10px] text-slate-400 leading-relaxed">
                Bạn không upload ảnh — <b className="text-slate-300">hệ thống tự tạo bảng phân cảnh khi render</b>. Ảnh này được ẩn để bảo mật quy trình.
              </p>
              {onUseOwnImage && (
                <button
                  onClick={onUseOwnImage}
                  className="text-[10px] text-[#FF5A1F] hover:text-[#FF8A5B] transition-colors cursor-pointer underline underline-offset-2"
                >
                  Dùng ảnh của tôi
                </button>
              )}
            </div>
          ) : multiPanelImageUrl ? (
            <div className="relative rounded-xl overflow-hidden border border-white/[0.06] bg-white/[0.02]">
              <img
                src={displayUrl || multiPanelImageUrl}
                alt="Multi-panel"
                {...noDownloadImg}
                className="w-full h-28 object-contain"
              />
              <button
                onClick={() => onMultiPanelImageChange('')}
                className="absolute top-2 right-2 p-1.5 rounded-lg bg-zinc-950/60 hover:bg-zinc-950/80 text-white/80 hover:text-white transition-all cursor-pointer"
              >
                <X className="h-3.5 w-3.5" />
              </button>
            </div>
          ) : (
            <div className="space-y-2">
              {sceneCount > 0 && onGenerateMultiPanel && (
                <button
                  onClick={onGenerateMultiPanel}
                  disabled={generatingMultiPanel}
                  className="w-full h-10 rounded-xl border border-[#FF5A1F]/30 hover:border-[#FF5A1F]/60 bg-[#FF5A1F]/5 hover:bg-[#FF5A1F]/10 flex items-center justify-center gap-2 text-[11px] font-medium text-[#FF5A1F] hover:text-[#FF8A5B] transition-all cursor-pointer disabled:opacity-50 disabled:cursor-not-allowed"
                >
                  {generatingMultiPanel ? (
                    <Loader2 className="h-3.5 w-3.5 animate-spin" />
                  ) : (
                    <Wand2 className="h-3.5 w-3.5" />
                  )}
                  {generatingMultiPanel ? 'Đang tạo...' : 'Tạo ảnh multi-panel từ AI'}
                </button>
              )}
              <button
                onClick={() => handleFileSelect('image/jpeg,image/png,image/webp', onMultiPanelImageChange)}
                className="w-full h-32 rounded-xl border-2 border-dashed border-white/[0.08] hover:border-[#FF5A1F]/40 flex flex-col items-center justify-center gap-2 text-[11px] text-slate-600 hover:text-slate-400 transition-colors bg-white/[0.01] cursor-pointer"
              >
                <Upload className="h-6 w-6" />
                <span>Chọn bảng phân cảnh</span>
                <span className="text-[9px] text-slate-600">JPEG/PNG/WEBP, max 20MB</span>
              </button>
            </div>
          )}
        </div>
      </motion.div>

      {/* Shared Skills — collapsible section */}
      <div className="flex items-center justify-between w-full px-4 py-2.5 border-b border-white/[0.04]">
        <button onClick={() => setSkillsOpen(!skillsOpen)} className="flex items-center gap-1 hover:bg-white/[0.02] transition-colors cursor-pointer">
          <div className="relative">
            <Info className="h-3 w-3 text-slate-600 hover:text-slate-400 transition-colors cursor-pointer"
              onClick={(e) => { e.stopPropagation(); setSkillsHelpOpen(v => !v); setImageHelpOpen(false); }} />
            {skillsHelpOpen && (
              <div className="absolute bottom-full left-1/2 -translate-x-1/2 mb-2 w-56 bg-[#1C1C20] border border-white/[0.08] rounded-xl shadow-md p-3 z-50">
                <p className="text-[10px] text-slate-300 leading-relaxed">
                  Các tùy chọn này được áp dụng cho toàn bộ video. Camera, phong cách, tâm trạng, ánh sáng và lời dẫn được chia sẻ giữa tất cả các khung hình.
                </p>
              </div>
            )}
          </div>
          <span className="text-[11px] font-semibold text-slate-400">Kỹ thuật quay dựng</span>
        </button>
        <motion.div animate={{ rotate: skillsOpen ? 180 : 0 }} transition={{ duration: 0.15 }}>
          <ChevronDown className="h-3.5 w-3.5 text-slate-600" />
        </motion.div>
      </div>

      <motion.div
        initial={false}
        animate={skillsOpen ? { height: 'auto', opacity: 1, transitionEnd: { overflow: 'visible' } } : { height: 0, opacity: 0, overflow: 'hidden' }}
        transition={{ duration: 0.2 }}
      >
        <div className="px-4 py-3 space-y-3 border-b border-white/[0.04]">
          <RichSelect
            label="Chuyển động Camera"
            value={sharedCamera}
            onChange={v => onSharedSkillChange('camera_movement', v)}
            options={CAMERA_OPTIONS}
            icon={Camera}
            tooltipSide="left"
            compact
          />
          <RichSelect
            label="Phong cách hình ảnh"
            value={sharedStyle}
            onChange={v => onSharedSkillChange('style', v)}
            options={STYLE_OPTIONS}
            icon={Palette}
            tooltipSide="left"
            compact
          />
          <RichSelect
            label="Tâm trạng / Cảm xúc"
            value={sharedMood}
            onChange={v => onSharedSkillChange('mood', v)}
            options={MOOD_OPTIONS}
            icon={Smile}
            tooltipSide="left"
            compact
          />
          <RichSelect
            label="Hiệu ứng ánh sáng"
            value={sharedLighting}
            onChange={v => onSharedSkillChange('lighting', v)}
            options={LIGHTING_OPTIONS}
            icon={Sun}
            tooltipSide="left"
            compact
          />
          <div className="space-y-1.5">
            <label className="text-[10px] font-semibold text-slate-500 flex items-center gap-1">
              <Mic className="h-3 w-3" />Lời dẫn (Narration)
            </label>
            <textarea
              value={sharedNarration}
              onChange={e => onSharedSkillChange('narration', e.target.value)}
              placeholder="Lời thuyết minh cho toàn bộ video..."
              rows={3}
              className="w-full bg-white/[0.04] border border-white/[0.08] rounded-xl px-3 py-2 text-[11px] text-slate-200 placeholder:text-slate-600 outline-none focus:border-[#FF5A1F]/50 transition-all resize-none"
            />
          </div>
          <div className="space-y-1.5">
            <label className="text-[10px] font-semibold text-slate-500 flex items-center gap-1">
              <Music className="h-3 w-3" />Audio dẫn (Driving Audio)
            </label>
            <p className="text-[9px] text-slate-600">WAV/MP3, 2-30s.</p>
            {drivingAudio ? (
              <div className="flex items-center justify-between px-3 py-2 rounded-xl bg-white/[0.02] border border-white/[0.06]">
                <span className="text-[11px] text-slate-400 truncate flex-1">{drivingAudio}</span>
                <button onClick={() => onDrivingAudioChange('')}
                  className="p-1 rounded hover:bg-red-500/10 text-slate-600 hover:text-red-400 cursor-pointer">
                  <X className="h-3 w-3" />
                </button>
              </div>
            ) : (
              <button onClick={() => handleFileSelect('audio/wav,audio/mp3', onDrivingAudioChange)}
                className="w-full h-10 rounded-xl border border-dashed border-white/[0.08] hover:border-[#FF5A1F]/40 flex items-center justify-center gap-2 text-[11px] text-slate-600 hover:text-slate-400 transition-colors bg-white/[0.01] cursor-pointer">
                <Upload className="h-3.5 w-3.5" /> Chọn audio
              </button>
            )}
          </div>

        </div>
      </motion.div>

      {/* Compiled prompt section */}
      <div className="flex-1 flex flex-col p-4 gap-3">
        {!compiledPrompt && (
          <div className="flex-1 flex flex-col items-center justify-center text-center gap-3">
            <div className="w-12 h-12 rounded-2xl bg-white/[0.03] border border-white/[0.06] flex items-center justify-center">
              <Sparkles className="h-5 w-5 text-slate-600" />
            </div>
            <p className="text-[11px] text-slate-500 leading-relaxed max-w-[200px]">
              Tải lên bảng phân cảnh và bấm 'Viết prompt' để AI tạo prompt
            </p>
            <button
              onClick={onCompile}
              disabled={!multiPanelImageUrl}
              className={cn(
                'flex items-center gap-1.5 px-4 py-2 rounded-xl text-[11px] font-semibold transition-all cursor-pointer',
                'bg-gradient-to-r from-[#FF5A1F] to-[#FF6B35] text-white',
                'hover:from-[#FF6B35] hover:to-[#FF7B45] shadow-[0_2px_12px_rgba(255,90,31,0.25)]',
                'disabled:opacity-40 disabled:cursor-not-allowed',
              )}
            >
              <Sparkles className="h-3.5 w-3.5" />
              Viết prompt
            </button>
            {!multiPanelImageUrl && (
              <p className="text-[10px] text-slate-600">Cần tải bảng phân cảnh trước</p>
            )}
          </div>
        )}

        {compiledPrompt && (
          <>
            <textarea
              value={compiledPrompt}
              onChange={(e) => onEdit(e.target.value)}
              className="flex-1 w-full bg-white/[0.03] border border-white/[0.06] rounded-xl p-3
                text-[11px] text-slate-200 placeholder:text-slate-600
                outline-none focus:border-[#FF5A1F]/50 transition-all resize-none
                min-h-48"
              placeholder="Prompt narrative..."
            />

            <div className="flex items-center gap-2">
              <button
                onClick={onCompile}
                className="cursor-pointer flex items-center gap-1.5 px-3 py-1.5 rounded-xl text-[10px] font-medium
                  bg-[#FF5A1F]/10 border border-[#FF5A1F]/20 text-[#FF5A1F]
                  hover:bg-[#FF5A1F]/20 transition-all"
              >
                <Sparkles className="h-3 w-3" />
                Viết lại
              </button>
            </div>
          </>
        )}
      </div>

      {/* Bottom meta */}
      <div className="px-4 py-3 border-t border-white/[0.04] flex items-center justify-between">
        <div className="flex items-center gap-1.5 text-[10px] text-slate-500">
          <span className="text-slate-600">{sceneCount} cảnh</span>
        </div>
        <div className="flex items-center gap-1.5 text-[10px] text-slate-500">
          <span>{totalDuration}s</span>
        </div>
      </div>
    </motion.div>
  );
}
